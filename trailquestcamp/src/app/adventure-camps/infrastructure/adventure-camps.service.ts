import {inject, Service} from '@angular/core';
import {HttpClient} from '@angular/common/http';
import {Observable} from 'rxjs';
import {BaseApi} from '../../../shared/infrastructure/base-api';
import {AdventureCampsEntity} from '../domain/model/adventure-camps.entity';
import {ReservationsEntity} from '../domain/model/reservations.entity';
import {AdventureCampsApiEndpoint} from './adventure-camps.api';
import {ReservationsApiEndpoint} from './reservations.api';

/**
 * Infrastructure facade for adventure camp and reservation endpoint operations.
 *
 * @author Sofia Diaz Yurivilca
 */
@Service()
export class AdventureCampsService extends BaseApi {
  private readonly http = inject(HttpClient);
  private readonly adventureCampsEndpoint = new AdventureCampsApiEndpoint(this.http);
  private readonly reservationsEndpoint = new ReservationsApiEndpoint(this.http);

  /**
   * Retrieves all adventure camps.
   * @returns Stream with the adventure camp collection.
   */
  getAdventureCamps = (): Observable<AdventureCampsEntity[]> =>
    this.adventureCampsEndpoint.getAll();

  /**
   * Retrieves a single adventure camp by ID.
   * @param id - The ID of the adventure camp.
   * @returns An Observable of the adventure camp.
   */
  getAdventureCamp = (id: number): Observable<AdventureCampsEntity> =>
    this.adventureCampsEndpoint.getById(id);

  /**
   * Retrieves all reservations.
   * @returns Stream with the reservation collection.
   */
  getReservations = (): Observable<ReservationsEntity[]> =>
    this.reservationsEndpoint.getAll();

  /**
   * Retrieves a single reservation by ID.
   * @param id - The ID of the reservation.
   * @returns An Observable of the reservation.
   */
  getReservation = (id: number): Observable<ReservationsEntity> =>
    this.reservationsEndpoint.getById(id);

  /**
   * Creates a new reservation.
   * @param reservation - The reservation to create.
   * @returns An Observable of the created reservation, with the id generated by the API.
   */
  createReservation = (reservation: ReservationsEntity): Observable<ReservationsEntity> =>
    this.reservationsEndpoint.create(reservation);
}
